# Определяем функцию взвешенной суммы (скалярное произведение)
def w_sum(a, b):
    assert(len(a) == len(b))
    output = 0
    for i in range(len(a)):
        output += (a[i] * b[i])
    return output

# Определяем нейронную сеть (один нейрон)
def neural_network(input, weights):
    pred = w_sum(input, weights)
    return pred

# Данные о трёх игроках (3 признака)
weights = [0.1, 0.2, 0]  # веса для: количество пальцев ног, wins, количество фанатов

# Статистика за 4 игры
toes = [8.5, 9.5, 9.9, 9.0]    # процент побед (или количество пальцев ног)
wlrec = [0.65, 0.8, 0.8, 0.9]  # количество побед
nfans = [1.2, 1.3, 0.5, 1.0]   # количество фанатов (в миллионах)

# Берём данные из первой игры (индекс 0)
input = [toes[0], wlrec[0], nfans[0]]

# Делаем предсказание
pred = neural_network(input, weights)

# Выводим результат
print(f"Предсказание для первой игры: {pred}")
print(f"Проверка: {toes[0]}*0.1 + {wlrec[0]}*0.2 + {nfans[0]}*0 = {pred}")